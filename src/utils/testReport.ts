export function generateJUnitXML(results: RunnerResult[], collectionName: string): string {
  const total = results.length;
  const failures = results.filter((r) => !r.success).length;
  const totalTime = (results.reduce((s, r) => s + r.responseTime, 0) / 1000).toFixed(3);

  const escapeXml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

  const testcases = results.map((r) => {
    const time = (r.responseTime / 1000).toFixed(3);
    let tc = `    <testcase name="${escapeXml(r.endpointName)}" classname="${escapeXml(collectionName)}.${escapeXml(r.method)}" time="${time}">`;
    if (!r.success) {
      tc += `\n      <failure message="HTTP ${r.statusCode || 'Error'}${r.error ? ': ' + escapeXml(r.error) : ''}" type="AssertionError">`;
      tc += `Status: ${r.statusCode}, Assertions: ${r.assertionsPassed}/${r.assertionsTotal}`;
      tc += `</failure>`;
    }
    tc += `\n    </testcase>`;
    return tc;
  }).join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<testsuites>
  <testsuite name="${escapeXml(collectionName)}" tests="${total}" failures="${failures}" time="${totalTime}" timestamp="${new Date().toISOString()}">
${testcases}
  </testsuite>
</testsuites>`;
}
